"""Основные настройки игры «Астероиды»."""

# Размеры игрового окна в пикселях.
WIDTH = 800
HEIGHT = 600

# Максимальное количество кадров в секунду.
FPS = 60

# Цвет фона в формате RGB.
BACKGROUND_COLOR = (10, 15, 30)

# Скорость поворота корабля в градусах в секунду.
SHIP_ROTATION_SPEED = 180

# Ускорение корабля в пикселях в секунду за секунду.
SHIP_ACCELERATION = 200

# Сила сопротивления: большее значение быстрее тормозит корабль.
